def synthesize_transcript_and_disjoint_queries(
    skills_with_problems: list[dict],
    session_problems_map: dict,
) -> list[dict]:
    """Generate 'transcript' and 'disjoint' queries for a batch of skills.

    'transcript': grounded in a genuine problem statement from the source session.
      The query must describe what a developer experiencing that problem would search
      for, and must NOT reuse tokens from the skill's own name or use_when.

    'disjoint': a symptom/situation paraphrase that describes the skill's value in
      fresh vocabulary — zero token overlap with the skill name or use_when phrasing.

    Each item in skills_with_problems is a dict:
      {skill, problem_statement}  (problem_statement may be None if session had none)

    Returns a list of query dicts with keys: id, kind, text, anchor, relevant.
    (split is assigned later by the caller.)

    Calls the real claude CLI once per batch. Raises RuntimeError if synthesis fails.
    """
    if not skills_with_problems:
        return []

    skill_entries = []
    for i, item in enumerate(skills_with_problems):
        s = item["skill"]
        prob = item.get("problem_statement") or ""
        entry = (
            f'SKILL_{i+1}:\n'
            f'  name: {s["name"]}\n'
            f'  type: {s.get("type", "")}\n'
            f'  description: {s.get("description", "")}\n'
            f'  use_when:\n'
            + "".join(f'    - {u}\n' for u in s.get("use_when", []))
            + (f'  session_problem: {prob}\n' if prob else '')
        )
        skill_entries.append(entry)

    skills_text = "\n".join(skill_entries)
    prompt = f"""You are building a retrieval-quality evaluation fixture for an AI skill retrieval system.
For each skill below, generate TWO search queries that a developer would realistically type when they need this skill:

1. TRANSCRIPT query (kind=transcript): Ground this in the provided session_problem text (if present).
   Phrase it as a developer describing their actual situation/symptom, NOT as documentation search.
   The query MUST NOT contain any tokens from the skill's 'name' field.
   The query MUST NOT copy phrases from the skill's 'use_when' list.
   If no session_problem is provided, generate a disjoint query instead (mark kind=disjoint).

2. DISJOINT query (kind=disjoint): Describe the same situation in completely FRESH vocabulary.
   Zero token overlap with the skill name or use_when phrasing.
   Think: "how would a developer describe this symptom to a colleague who knows nothing about this skill?"

Both queries must be realistic developer phrasing — a question or situation description, not a keyword list.
Both queries must clearly point to this specific skill as the most relevant answer.

Skills:
{skills_text}

Respond with EXACTLY a JSON array, one object per skill, in this format:
[
  {{
    "skill_index": 1,
    "skill_name": "<exact name from above>",
    "transcript_query": "<realistic developer query grounded in the problem statement, or empty string if no problem>",
    "disjoint_query": "<fresh vocabulary paraphrase of skill intent>"
  }},
  ...
]

JSON:"""

    raw = invoke_claude(prompt)
    items = parse_json_array_from_text(raw, context="transcript/disjoint batch")

    queries = []
    for item_data in items:
        skill_name = item_data.get("skill_name", "")
        idx = item_data.get("skill_index", 0)
        transcript_q = (item_data.get("transcript_query") or "").strip()
        disjoint_q = (item_data.get("disjoint_query") or "").strip()

        if not skill_name:
            continue

        if transcript_q:
            queries.append({
                "id": f"t11-transcript-{_slug(skill_name)}",
                "kind": "transcript",
                "text": transcript_q,
                "anchor": skill_name,
                "relevant": [skill_name],
            })

        if disjoint_q:
            queries.append({
                "id": f"t11-disjoint-{_slug(skill_name)}",
                "kind": "disjoint",
                "text": disjoint_q,
                "anchor": skill_name,
                "relevant": [skill_name],
            })

    return queries


