# ─── Claude CLI synthesis ─────────────────────────────────────────────────────

def invoke_claude(prompt: str) -> str:
    """Call the real claude CLI and return the raw model text.

    Uses the same invocation as scripts/retrieval_quality_live.py judge_query:
    ``claude --print --output-format json --model <model>``.
    The ``--output-format json`` envelope wraps model text in the ``.result`` key.

    Fails loud (raises RuntimeError) on any CLI error or non-zero exit code.
    Never silently falls back to a fake response.

    Args:
        prompt: The full prompt text to send to the model.

    Returns:
        The raw text content from the model's response (the ``.result`` value
        extracted from the JSON envelope, or raw stdout if envelope parsing fails).
    """
    proc = subprocess.run(
        ["claude", "--print", "--output-format", "json", "--model", CLAUDE_MODEL],
        input=prompt,
        capture_output=True,
        text=True,
        timeout=300,
    )
    if proc.returncode != 0:
        raise RuntimeError(
            f"claude CLI failed (rc={proc.returncode}): {proc.stderr[:500]}"
        )
    try:
        envelope = json.loads(proc.stdout)
        if isinstance(envelope, dict) and "result" in envelope:
            return envelope["result"]
    except json.JSONDecodeError:
        pass
    return proc.stdout


def parse_json_array_from_text(text: str, context: str = "") -> list:
    """Extract a JSON array from model output that may contain surrounding prose.

    Finds the first '[' and last ']' and parses between them.  Raises RuntimeError
    if no array brackets are found or if the JSON is malformed — never silently
    returns an empty list that masks a parse failure.

    Args:
        text: Raw model output text possibly containing a JSON array plus prose.
        context: Optional description of what was being parsed, for error messages.
    """
    text = text.strip()
    start = text.find("[")
    end = text.rfind("]")
    if start < 0 or end < 0 or end <= start:
        raise RuntimeError(
            f"No JSON array brackets found in claude output"
            f"{' for ' + context if context else ''}:\n{text[:400]}"
        )
    try:
        return json.loads(text[start : end + 1])
    except json.JSONDecodeError as exc:
        raise RuntimeError(
            f"Malformed JSON array in claude output"
            f"{' for ' + context if context else ''}: {exc}\n{text[start:end+1][:400]}"
        ) from exc


# ─── corpus loading and skill classification ──────────────────────────────────

def load_corpus(inventory_path: Path) -> tuple[list[dict], set[str]]:
    """Load the corpus inventory and return (skill_list, name_set).

    skill_list: all 262 skills as dicts.
    name_set: the set of all valid skill names for anchor validation.
    """
    skills = json.loads(inventory_path.read_text())
    return skills, {s["name"] for s in skills}


def load_session_problems(problems_path: Path) -> dict:
    """Load the session_problems.json mapping."""
    return json.loads(problems_path.read_text())


def usable_skills(skills: list[dict]) -> list[dict]:
    """Return skills that are candidates for positive queries.

    A skill is usable when it has a real type (not None) and a substantive
    description (>50 chars). Skills whose names start with any of the
    _PREFERENCE_SKILL_PREFIXES are excluded: those describe injected user
    preferences ('Do not respond to…', 'Always use…'), not technical engineering
    patterns, and produce uninformative queries.
    """
    return [
        s for s in skills
        if s.get("type") is not None
        and s.get("description")
        and len(s["description"]) > 50
        and not any(s["name"].startswith(prefix) for prefix in _PREFERENCE_SKILL_PREFIXES)
    ]


def skills_by_session(skills: list[dict]) -> dict[str, list[dict]]:
    """Group a skill list by session_key."""
    grouped: dict[str, list[dict]] = defaultdict(list)
    for s in skills:
        grouped[s["session_key"]].append(s)
    return dict(grouped)


def has_multiview_exclusive_terms(skill: dict) -> bool:
    """Return True if the skill has a specific term in tools/artifacts/invariants
    that does NOT appear in its name or description or use_when.

    Used to identify candidates for the 'multiview' stratum — queries whose gold
    term can only be found in the multi-view fields, stressing multi-view recall.
    """
    name_desc_usewhen = (
        skill["name"].lower()
        + " "
        + skill.get("description", "").lower()
        + " "
        + " ".join(skill.get("use_when", [])).lower()
    )
    for artifact in skill.get("artifacts", []):
        # Specific filenames (contain a dot) not mentioned in name/desc are good
        if "." in artifact and artifact.lower() not in name_desc_usewhen:
            return True
    for tool in skill.get("tools", []):
        # Specific tool names ≥5 chars not in name/desc
        if len(tool) >= 5 and tool.lower() not in name_desc_usewhen:
            return True
    for inv in skill.get("invariants", []):
        # Invariants often have precise technical terms
        words = [w for w in inv.split() if len(w) > 7]
        if any(w.lower() not in name_desc_usewhen for w in words[:3]):
            return True
    return False


