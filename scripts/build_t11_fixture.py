# ─── validation ───────────────────────────────────────────────────────────────

def validate_anchors(queries: list[dict], valid_names: set[str]) -> None:
    """Validate that every positive query's anchor and relevant list contains
    only names that exist in the corpus.

    Fails loud (raises RuntimeError) listing ALL misses — never silently drops
    a query with an invalid anchor. The caller must fix the source before proceeding.

    Args:
        queries: All query dicts from the fixture (positives and negatives mixed).
        valid_names: The set of all 262 skill names from corpus_inventory.
    """
    anchor_misses = []
    relevant_misses = []
    for q in queries:
        if q["kind"] == "negative":
            continue
        anchor = q.get("anchor")
        if anchor and anchor not in valid_names:
            anchor_misses.append(f"  query {q['id']!r}: anchor {anchor!r}")
        for r in q.get("relevant", []):
            if r not in valid_names:
                relevant_misses.append(f"  query {q['id']!r}: relevant {r!r}")

    if anchor_misses or relevant_misses:
        lines = ["ANCHOR VALIDATION FAILED — misses in 262 corpus:"]
        if anchor_misses:
            lines.append("  Bad anchors:")
            lines.extend(anchor_misses)
        if relevant_misses:
            lines.append("  Bad relevant entries:")
            lines.extend(relevant_misses)
        raise RuntimeError("\n".join(lines))


# ─── split assignment ─────────────────────────────────────────────────────────

def assign_splits(queries: list[dict], tuning_ratio: float) -> list[dict]:
    """Assign tuning/held_out splits to queries.

    Positives are split per anchor skill: each anchor's queries go entirely into
    one split (so the two splits test on disjoint anchor sets, preventing
    information leakage). The anchor assignment is randomized, then balanced to
    the target ratio.

    Negatives are split proportionally across both splits.

    Returns the same list with 'split' field filled in on every query.
    """
    # Group positive queries by anchor
    by_anchor: dict[str, list[dict]] = defaultdict(list)
    negatives = []
    for q in queries:
        if q["kind"] == "negative":
            negatives.append(q)
        else:
            by_anchor[q["anchor"]].append(q)

    anchors = list(by_anchor.keys())
    random.shuffle(anchors)

    n_tuning = round(len(anchors) * tuning_ratio)
    tuning_anchors = set(anchors[:n_tuning])
    held_out_anchors = set(anchors[n_tuning:])

    result = []
    for q in queries:
        q = dict(q)  # copy to avoid mutation
        if q["kind"] == "negative":
            continue  # handled below
        split = "tuning" if q["anchor"] in tuning_anchors else "held_out"
        q["split"] = split
        result.append(q)

    # Split negatives proportionally
    neg_tuning_count = round(len(negatives) * tuning_ratio)
    for i, neg in enumerate(negatives):
        neg = dict(neg)
        neg["split"] = "tuning" if i < neg_tuning_count else "held_out"
        result.append(neg)

    return result


# ─── helpers ──────────────────────────────────────────────────────────────────

def _slug(name: str) -> str:
    """Convert a skill name to a short, URL-safe id fragment (max 40 chars)."""
    slug = name.lower().replace(" ", "-").replace("/", "-").replace("_", "-")
    # Remove characters other than alphanumeric and dash
    slug = "".join(c for c in slug if c.isalnum() or c == "-")
    return slug[:40].rstrip("-")


def _print_progress(msg: str) -> None:
    """Print a progress line to stderr so stdout remains clean for piped use."""
    print(f"[build_t11_fixture] {msg}", file=sys.stderr)


def _chunk(lst: list, size: int) -> list[list]:
    """Split a list into chunks of at most `size` items."""
    return [lst[i : i + size] for i in range(0, len(lst), size)]


# ─── main build pipeline ──────────────────────────────────────────────────────

def build_fixture() -> None:
    """Orchestrate the complete fixture build.

    Loads artifacts → selects gold skills → calls claude for each stratum →
    validates anchors → assigns splits → writes fixture + summary.

    Raises RuntimeError on any failure. Does NOT silently continue with partial
    results — the fixture must be complete and valid or the build fails.
    """
    _print_progress("Loading corpus inventory and session problems...")
    skills, valid_names = load_corpus(CORPUS_INVENTORY)
    session_problems = load_session_problems(SESSION_PROBLEMS)

    # ── select usable skills ─────────────────────────────────────────────────
    candidate_skills = usable_skills(skills)
    _print_progress(f"Usable skills for query authoring: {len(candidate_skills)}")

    by_session = skills_by_session(candidate_skills)

    # ── select gold skills for transcript/disjoint strata ───────────────────
    # For transcript: the session must have a real technical problem (>80 chars)
    # AND the skill must be in that session.
    # Pick 1-2 skills per session with problems to spread gold across sessions.
    transcript_targets: list[dict] = []  # {skill, problem_statement}

    for session_key, session_data in session_problems.items():
        technical_problems = [
            p for p in session_data.get("problems", [])
            if len(p) > 80 and not _is_trivial_problem(p)
        ]
        session_skills_in_corpus = by_session.get(session_key, [])
        if not technical_problems or not session_skills_in_corpus:
            continue

        # Pick the most technical problem from the session
        best_problem = max(technical_problems, key=len)

        # Pick 1-2 skills from this session
        chosen = session_skills_in_corpus[:2]
        for s in chosen:
            transcript_targets.append({
                "skill": s,
                "problem_statement": best_problem,
            })

    _print_progress(f"Transcript targets: {len(transcript_targets)} (across sessions)")

    # ── stratum 1+2: transcript + disjoint (batches of 8) ───────────────────
    all_transcript_disjoint: list[dict] = []
    batches = _chunk(transcript_targets, 5)
    for i, batch in enumerate(batches):
        _print_progress(
            f"Synthesizing transcript/disjoint batch {i+1}/{len(batches)} "
            f"({len(batch)} skills)..."
        )
        qs = synthesize_transcript_and_disjoint_queries(batch, session_problems)
        all_transcript_disjoint.extend(qs)
        _print_progress(f"  → {len(qs)} queries generated")

    _print_progress(
        f"Transcript/disjoint total: {len(all_transcript_disjoint)}"
    )

    # ── stratum 3: lexical (pick from all sessions, 1 per skill) ─────────────
    # Choose a balanced cross-section of skills for lexical queries
    lexical_skills = _select_balanced_sample(candidate_skills, target_count=30)
    lexical_queries: list[dict] = []
    for batch in _chunk(lexical_skills, 6):
        _print_progress(f"Synthesizing lexical batch ({len(batch)} skills)...")
        qs = synthesize_lexical_queries(batch)
        lexical_queries.extend(qs)
    _print_progress(f"Lexical total: {len(lexical_queries)}")

    # ── stratum 4: multiview (only for skills with exclusive MV terms) ────────
    mv_candidates = [s for s in candidate_skills if has_multiview_exclusive_terms(s)]
    mv_skills = _select_balanced_sample(mv_candidates, target_count=20)
    multiview_queries: list[dict] = []
    for batch in _chunk(mv_skills, 5):
        _print_progress(f"Synthesizing multiview batch ({len(batch)} skills)...")
        qs = synthesize_multiview_queries(batch)
        multiview_queries.extend(qs)
    _print_progress(f"Multiview total: {len(multiview_queries)}")

    # ── stratum 5: use_when (secondary stratum, smaller count) ───────────────
    uw_skills = _select_balanced_sample(
        [s for s in candidate_skills if s.get("use_when")], target_count=15
    )
    use_when_queries: list[dict] = []
    for batch in _chunk(uw_skills, 6):
        _print_progress(f"Synthesizing use_when batch ({len(batch)} skills)...")
        qs = synthesize_use_when_queries(batch)
        use_when_queries.extend(qs)
    _print_progress(f"Use_when total: {len(use_when_queries)}")

    # ── stratum 6: negatives ──────────────────────────────────────────────────
    _print_progress("Synthesizing negative queries...")
    negative_queries = synthesize_negative_queries(count=25)
    _print_progress(f"Negatives total: {len(negative_queries)}")

    # ── assemble all queries ──────────────────────────────────────────────────
    all_positive = (
        all_transcript_disjoint
        + lexical_queries
        + multiview_queries
        + use_when_queries
    )
    all_queries = all_positive + negative_queries

    _print_progress(f"Total before dedup: {len(all_queries)} queries")

    # Deduplicate by id (keep first occurrence)
    seen_ids: set[str] = set()
    deduped: list[dict] = []
    for q in all_queries:
        if q["id"] not in seen_ids:
            seen_ids.add(q["id"])
            deduped.append(q)
    all_queries = deduped

    # ── validate anchors ──────────────────────────────────────────────────────
    _print_progress("Validating all anchors against corpus names...")
    validate_anchors(all_queries, valid_names)
    _print_progress("Anchor validation passed.")

    # ── count checks ─────────────────────────────────────────────────────────
    positives = [q for q in all_queries if q["kind"] != "negative"]
    negatives = [q for q in all_queries if q["kind"] == "negative"]
    _print_progress(
        f"Counts: {len(positives)} positives, {len(negatives)} negatives"
    )

    if len(positives) < 100:
        raise RuntimeError(
            f"Fixture has only {len(positives)} positive queries; need ≥100. "
            "Adjust batch sizes or add more sessions."
        )
    if len(negatives) < 20:
        raise RuntimeError(
            f"Fixture has only {len(negatives)} negative queries; need ≥20."
        )

    # ── assign splits ─────────────────────────────────────────────────────────
    _print_progress("Assigning tuning/held_out splits...")
    random.seed(42)
    all_queries_with_split = assign_splits(all_queries, SPLIT_TUNING_RATIO)

    # ── build fixture document ────────────────────────────────────────────────
    stratum_counts = _count_by_field(all_queries_with_split, "kind")
    split_counts = _count_by_field(all_queries_with_split, "split")
    distinct_gold_skills = len(
        {q["anchor"] for q in all_queries_with_split if q.get("anchor")}
    )
    distinct_sessions = len(
        {
            next(
                (s["session_key"] for s in skills if s["name"] == q.get("anchor")),
                None,
            )
            for q in all_queries_with_split
            if q.get("anchor")
        }
        - {None}
    )

    fixture = {
        "_description": (
            "Anti-circularity retrieval-quality fixture for the 262-skill qwen3 corpus (T11). "
            "Headline queries (transcript/disjoint) are derived from GENUINE developer problem "
            "statements typed in the source sessions, NOT from the skills' own use_when or "
            "description — that ensures the fixture measures real retrieval discriminability, "
            "not self-recall. Lexical queries use terms from skill descriptions. Multiview "
            "queries use terms that appear ONLY in tools/artifacts/invariants. Use_when queries "
            "are a labeled secondary stratum (lightly reworded use_when). Negatives are "
            "adversarial plausible queries that match no corpus skill. Built 2026-06-11."
        ),
        "_authoring_protocol": (
            "Queries generated by the real claude CLI (claude-sonnet-4-6 via "
            "claude --print --output-format json). Anchors validated against the 262 corpus name "
            "set before commit. No fabricated/templated queries. "
            "Gold skills drawn from 24 source sessions via session_problems.json + "
            "corpus_inventory.json prepared by scripts/extract_t11_session_problems.py."
        ),
        "_strata": {
            "transcript": "Grounded in a genuine developer problem statement from the source session. "
                          "Does not reuse skill name tokens.",
            "disjoint": "Intent paraphrase in fresh vocabulary; zero token overlap with skill name/use_when.",
            "lexical": "Uses a distinctive technical term from the skill name/description.",
            "multiview": "Uses a term that appears ONLY in tools/artifacts/invariants (not name/desc/use_when).",
            "use_when": "SECONDARY STRATUM: lightly reworded paraphrase of one use_when condition.",
            "negative": "Adversarial: plausible software-dev query that matches no corpus skill.",
        },
        "_split": "tuning/held_out disjoint by anchor skill (~55/45); negatives proportionally split",
        "_counts": {
            "strata": stratum_counts,
            "splits": split_counts,
            "distinct_gold_skills": distinct_gold_skills,
            "distinct_sessions": distinct_sessions,
        },
        "queries": all_queries_with_split,
    }

    # ── write fixture ─────────────────────────────────────────────────────────
    FIXTURE_OUT.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE_OUT.write_text(json.dumps(fixture, indent=1, ensure_ascii=False))
    _print_progress(f"Fixture written to {FIXTURE_OUT}")

    # ── write summary ─────────────────────────────────────────────────────────
    summary = {
        "stratum_counts": stratum_counts,
        "split_counts": split_counts,
        "distinct_gold_skill_count": distinct_gold_skills,
        "distinct_session_count": distinct_sessions,
        "total_queries": len(all_queries_with_split),
        "samples_by_stratum": _sample_queries_by_stratum(all_queries_with_split),
    }
    SUMMARY_OUT.parent.mkdir(parents=True, exist_ok=True)
    SUMMARY_OUT.write_text(json.dumps(summary, indent=2, ensure_ascii=False))
    _print_progress(f"Summary written to {SUMMARY_OUT}")

    # ── final report ─────────────────────────────────────────────────────────
    _print_progress("Build complete.")
    _print_progress(f"  Positives: {len(positives)}")
    _print_progress(f"  Negatives: {len(negatives)}")
    _print_progress(f"  Strata: {stratum_counts}")
    _print_progress(f"  Splits: {split_counts}")
    _print_progress(f"  Distinct gold skills: {distinct_gold_skills}")
    _print_progress(f"  Distinct sessions: {distinct_sessions}")


# ─── internal helpers ─────────────────────────────────────────────────────────

def _is_trivial_problem(problem: str) -> bool:
    """Return True if the problem statement is operational steering with no
    technical content (e.g. 'commit and push', 'yes proceed').

    These statements don't seed meaningful 'transcript' queries because they
    describe meta-actions, not developer technical problems.
    """
    lowered = problem.lower().strip()
    trivial_patterns = (
        "commit and push",
        "commit and proceed",
        "proceed to next",
        "give me the prompt",
        "commit it and then",
        "yes commit",
        "yes yes it",
        "commit everything",
        "add those untracked",
        "add everything to the commit",
        "is everything committed",
        "is everything logged",
        "are the new tickets",
        "\\\\wsl",
    )
    return any(lowered.startswith(p) for p in trivial_patterns)


def _select_balanced_sample(skills: list[dict], target_count: int) -> list[dict]:
    """Select up to `target_count` skills spread across as many sessions as
    possible (round-robin across sessions), to ensure gold skills span the corpus.

    Returns a list of at most `target_count` skills.
    """
    by_session: dict[str, list[dict]] = defaultdict(list)
    for s in skills:
        by_session[s["session_key"]].append(s)

    session_queues = {k: list(v) for k, v in by_session.items()}
    result = []
    while len(result) < target_count:
        added_this_round = False
        for session_key in list(session_queues.keys()):
            if not session_queues[session_key]:
                continue
            result.append(session_queues[session_key].pop(0))
            added_this_round = True
            if len(result) >= target_count:
                break
        if not added_this_round:
            break

    return result


def _count_by_field(queries: list[dict], field: str) -> dict[str, int]:
    """Return a frequency count of query values for the given field key."""
    counts: dict[str, int] = defaultdict(int)
    for q in queries:
        counts[str(q.get(field, "unknown"))] += 1
    return dict(sorted(counts.items()))


def _sample_queries_by_stratum(queries: list[dict], n: int = 3) -> dict[str, list[dict]]:
    """Return up to `n` sample queries per stratum for the build summary."""
    by_stratum: dict[str, list[dict]] = defaultdict(list)
    for q in queries:
        by_stratum[q["kind"]].append(q)

    return {
        kind: [
            {"id": q["id"], "text": q["text"], "anchor": q.get("anchor"), "split": q.get("split")}
            for q in qs[:n]
        ]
        for kind, qs in by_stratum.items()
    }


# ─── entrypoint ───────────────────────────────────────────────────────────────

if __name__ == "__main__":
    build_fixture()
